                            <h3 class="blogs-heading-level-1 mt-6">Tax Consequences</h3>
                            <h4 class="blogs-heading-level-2">Tax Consequences to the Deceased Shareholder</h4>
                            <p>Upon his/her death, A has a deemed disposition of shares in the corporation equal to the fair market value of $200,000. This deemed disposition will generate a capital gain of $199,900, equal to the FMV of the shares minus their adjusted cost base. One-half of this capital gain will be reported as income in A's final tax return. (Some or all of this gain may be off-set by the life-time capital gain exemption allowed on the shares of a small business corporation).</p>
                            <h4 class="blogs-heading-level-2">Tax Consequences to the Deceased Shareholder's Estate</h4>
                            <p>A's estate will acquire the shares from A with an adjusted cost base equal to the fair market value of the disposition, i.e. $200,000. When the estate sells the shares to B pursuant to the buy/sell agreement, a gain or loss will be realized by the estate depending upon whether the sale was less than or equal to the FMV of the shares. If the fair market value of the shares was greater than the $200,000 stipulated in the buy/sell agreement, a loss would be incurred by the estate on the subsequent sale to B. If this happened, the capital loss could be carried back to offset the deceased's capital gain as reported in his/her final tax return. (subsection 164(6) of the Act).</p>
                            <h4 class="blogs-heading-level-2">Tax Consequences to the Surviving Shareholder</h4>
                            <p>B will purchase A's shares at the price agreed to in the buy/sell agreement ($200,000 ) from the insurance payout that B receives tax-free. The ACB of the acquired shares is averaged with the ACB of B's original shares to determine the capital gain or loss realized when B eventually sells his shares.</p>

