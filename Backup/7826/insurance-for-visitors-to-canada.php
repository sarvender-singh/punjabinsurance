<script>
$(document).ready(function () {

    // ── Flatpickr: Start date of coverage (today or future) ───────────────────
    var fpStart = flatpickr('#departeredate', {
        dateFormat:    'd/m/Y',
        minDate:       'today',
        allowInput:    true,
        disableMobile: true,
        onChange: function () {
            // Update end picker minDate to day-after-start
            var v = $('#departeredate').val().trim();
            if (fpEnd && isValidDate(v)) {
                var p = v.split('/');
                var next = new Date(parseInt(p[2],10), parseInt(p[1],10)-1, parseInt(p[0],10));
                next.setDate(next.getDate() + 1);
                fpEnd.set('minDate', next);
            }
            validateStartDate(true);
            if ($('#returndate').val().trim()) validateEndDate(true);
        }
    });

    // ── Flatpickr: End date of coverage (must be after start) ─────────────────
    var fpEnd = flatpickr('#returndate', {
        dateFormat:    'd/m/Y',
        minDate:       'today',
        allowInput:    true,
        disableMobile: true,
        onChange: function () { validateEndDate(true); }
    });

    // ── Flatpickr: DOB traveller 1 (past only, yesterday max) ────────────────
    var yesterday = new Date();
    yesterday.setDate(yesterday.getDate() - 1);

    flatpickr('#dateofbirth1', {
        dateFormat:    'd/m/Y',
        maxDate:       yesterday,
        allowInput:    true,
        disableMobile: true,
        onChange: function () { validateDOB1(true); }
    });

    // ── Flatpickr: DOB traveller 2 (past only, yesterday max) ────────────────
    flatpickr('#dateofbirth2', {
        dateFormat:    'd/m/Y',
        maxDate:       yesterday,
        allowInput:    true,
        disableMobile: true,
        onChange: function () { if (isTwoTravellers()) validateDOB2(true); }
    });

    // ── Show/hide traveller 2 fields based on ntravellers select ─────────────
    function isTwoTravellers() {
        return parseInt($('#ntravellers').val(), 10) === 2;
    }

    function toggleTraveller2() {
        if (isTwoTravellers()) {
            $('.traveller-2').show();
        } else {
            $('.traveller-2').hide();
            // Clear traveller-2 validation state when hidden
            resetField($('#dateofbirth2'));
            resetField($('#medical_cond2'));
        }
    }

    // Set initial state on page load (1 traveller by default)
    toggleTraveller2();

    $('#ntravellers').on('change', function () {
        toggleTraveller2();
        // If we switched to 2, re-validate dob2 only if it has a value
        if (isTwoTravellers() && $('#dateofbirth2').val().trim()) {
            validateDOB2(true);
        }
    });

    // ── Error helpers ─────────────────────────────────────────────────────────
    function showError($field, message) {
        $field.removeClass('is-valid').addClass('is-invalid');
        var $group = $field.closest('.input-group');
        $group.find('.error-msg').remove();
        $group.append('<span class="error-msg">' + message + '</span>');
    }
    function clearError($field) {
        $field.removeClass('is-invalid').addClass('is-valid');
        $field.closest('.input-group').find('.error-msg').remove();
    }
    function resetField($field) {
        $field.removeClass('is-invalid is-valid');
        $field.closest('.input-group').find('.error-msg').remove();
    }

    // ── Format helpers ────────────────────────────────────────────────────────
    function isValidEmail(v) { return /^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(v); }
    function isValidPhone(v) { return /^[\d\s\-\+\(\)]{7,15}$/.test(v.trim()); }
    function isValidDate(str) {
        if (!/^\d{2}\/\d{2}\/\d{4}$/.test(str)) return false;
        var p = str.split('/');
        var d = parseInt(p[0],10), m = parseInt(p[1],10), y = parseInt(p[2],10);
        if (m < 1 || m > 12 || d < 1 || d > 31 || y < 1900 || y > 2100) return false;
        var dt = new Date(y, m-1, d);
        return dt.getFullYear()===y && dt.getMonth()===m-1 && dt.getDate()===d;
    }
    function parseDate(str) {
        var p = str.split('/');
        return new Date(parseInt(p[2],10), parseInt(p[1],10)-1, parseInt(p[0],10));
    }
    function isTodayOrFuture(str) {
        var t = new Date(); t.setHours(0,0,0,0);
        return parseDate(str) >= t;
    }
    function isBeforeToday(str) {
        var t = new Date(); t.setHours(0,0,0,0);
        return parseDate(str) < t;
    }

    // ── Per-field validators ──────────────────────────────────────────────────
    function validateName(show) {
        var $f = $('#tname'), v = $f.val().trim();
        if (!v)           { if (show) showError($f, 'Name is required.'); return false; }
        if (v.length < 2) { if (show) showError($f, 'Name must be at least 2 characters.'); return false; }
        if (!/^[a-zA-Z\s\-']+$/.test(v)) { if (show) showError($f, 'Name can only contain letters.'); return false; }
        clearError($f); return true;
    }
    function validateEmail(show) {
        var $f = $('#contact_email'), v = $f.val().trim();
        if (!v)               { if (show) showError($f, 'Email is required.'); return false; }
        if (!isValidEmail(v)) { if (show) showError($f, 'Please enter a valid email address.'); return false; }
        clearError($f); return true;
    }

	function validatePhone(show) {
    var $f = $('#tphone'), v = $f.val().trim();
    
    // Only accepts: 4165551234 or 416-555-1234
    var canadianPhone = /^\d{10}$|^\d{3}-\d{3}-\d{4}$/;
    
    if (!v)                     { if(show) showError($f, 'Phone number is required.'); return false; }
    if (!canadianPhone.test(v)) { if(show) showError($f, 'Please enter a valid phone number (e.g. 4165551234 or 416-555-1234).'); return false; }
    
    clearError($f); return true;
}
    function validateDestination(show) {
        var $f = $('#primary_destination'), v = $f.val();
        if (!v) { if (show) showError($f, 'Please select a province.'); return false; }
        clearError($f); return true;
    }
    function validateStartDate(show) {
        var $f = $('#departeredate'), v = $f.val().trim();
        if (!v)                  { if (show) showError($f, 'Start date of coverage is required.'); return false; }
        if (!isValidDate(v))     { if (show) showError($f, 'Please enter a valid date (DD/MM/YYYY).'); return false; }
        if (!isTodayOrFuture(v)) { if (show) showError($f, 'Start date cannot be in the past.'); return false; }
        clearError($f); return true;
    }
    function validateEndDate(show) {
        var $f = $('#returndate'), v = $f.val().trim();
        var dep = $('#departeredate').val().trim();
        if (!v)              { if (show) showError($f, 'End date of coverage is required.'); return false; }
        if (!isValidDate(v)) { if (show) showError($f, 'Please enter a valid date (DD/MM/YYYY).'); return false; }
        if (isValidDate(dep) && parseDate(v) <= parseDate(dep)) {
            if (show) showError($f, 'End date must be after the start date.');
            return false;
        }
        clearError($f); return true;
    }
    function validateDOB1(show) {
        var $f = $('#dateofbirth1'), v = $f.val().trim();
        if (!v)               { if (show) showError($f, 'Birth date of traveller is required.'); return false; }
        if (!isValidDate(v))  { if (show) showError($f, 'Please enter a valid date (DD/MM/YYYY).'); return false; }
        if (!isBeforeToday(v)){ if (show) showError($f, 'Birth date cannot be today or in the future.'); return false; }
        clearError($f); return true;
    }
    function validateDOB2(show) {
        // Only validate when traveller-2 is visible
        if (!isTwoTravellers()) return true;
        var $f = $('#dateofbirth2'), v = $f.val().trim();
        if (!v)               { if (show) showError($f, 'Birth date of traveller 2 is required.'); return false; }
        if (!isValidDate(v))  { if (show) showError($f, 'Please enter a valid date (DD/MM/YYYY).'); return false; }
        if (!isBeforeToday(v)){ if (show) showError($f, 'Birth date cannot be today or in the future.'); return false; }
        clearError($f); return true;
    }

    // ── Blur / change events ──────────────────────────────────────────────────
    $('#tname').on('blur',                   function () { validateName(true); });
    $('#contact_email').on('blur',           function () { validateEmail(true); });
    $('#tphone').on('blur',                  function () { validatePhone(true); });
    $('#primary_destination').on('change',   function () { validateDestination(true); });
    $('#departeredate').on('blur change',    function () { validateStartDate(true); });
    $('#returndate').on('blur change',       function () { validateEndDate(true); });
    $('#dateofbirth1').on('blur change',     function () { validateDOB1(true); });
    $('#dateofbirth2').on('blur change',     function () { if (isTwoTravellers()) validateDOB2(true); });

    $('#tname, #contact_email, #tphone').on('input', function () { resetField($(this)); });

    // ── Submit ────────────────────────────────────────────────────────────────
    $('#lifeinssubmit').on('click', function (e) {
        e.preventDefault();

        var valid =
            validateName(true)        &
            validateEmail(true)       &
            validatePhone(true)       &
            validateDestination(true) &
            validateStartDate(true)   &
            validateEndDate(true)     &
            validateDOB1(true)        &
            validateDOB2(true);       // returns true automatically if only 1 traveller

        if (!valid) {
            var $first = $('.is-invalid').first();
            if ($first.length) {
                $('html, body').animate({
                    scrollTop: $first.closest('.input-group').offset().top - 120
                }, 380);
                $first.focus();
            }
            return;
        }

        // All valid — disable button and submit to external URL
        var $btn = $(this);
        $btn.prop('disabled', true);
        $btn.find('span').text('Submitting...');
        $btn.append('<span class="btn-spinner"></span>');
        $btn.closest('form').submit();
    });

});
